import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'

// Opt in only against the current explicitly supplied local, isolated QA instance.
// No messages are sent, revoked or deleted; this uses the existing seeded conversation.
test('private chat quote history search menus and mobile composer work in a real browser', {
  skip: !process.env.PHASE2_CHAT_QA_URL,
  timeout: 90000,
}, async () => {
  const base = new URL(process.env.PHASE2_CHAT_QA_URL)
  assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(base.hostname))
  assert.ok(process.env.PHASE2_CHAT_QA_USERNAME)
  const require = createRequire(import.meta.url)
  const { chromium } = require(process.env.PHASE2_CHAT_PLAYWRIGHT_MODULE || 'playwright-core')
  const browser = await chromium.launch({ executablePath: process.env.PHASE2_CHAT_CHROME || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
  const contexts = [], errors = [], mutations = [], pureReads = []
  try {
    const desktop = await browser.newContext({ viewport: { width: 1360, height: 950 }, colorScheme: 'light', reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] })
    contexts.push(desktop)
    const page = await desktop.newPage()
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => {
      const url = new URL(request.url())
      if (url.pathname === '/api/messages' && request.method() === 'POST') mutations.push(request.url())
      if (url.pathname.startsWith('/api/messages/conversation/') && (url.searchParams.has('q') || url.searchParams.has('around_id') || url.searchParams.has('before'))) pureReads.push(url)
    })
    await page.goto(new URL('/login', base).href, { waitUntil: 'networkidle' })
    await page.locator('#login-username').fill(process.env.PHASE2_CHAT_QA_USERNAME)
    await page.locator('#login-password').fill(process.env.PHASE2_CHAT_QA_PASSWORD || '')
    await page.locator('form button[type="submit"]').click()
    await page.waitForURL(url => url.pathname !== '/login')
    const peer = process.env.PHASE2_CHAT_QA_PEER_ID || '2'
    await page.goto(new URL('/chat/' + peer, base).href, { waitUntil: 'networkidle' })
    const input = page.getByRole('textbox', { name: '消息内容', exact: true })
    await input.waitFor()
    const initialCount = await page.locator('[data-message-id]').count()
    assert.ok(initialCount > 0)
    await page.getByRole('button', { name: '加载更早的消息', exact: true }).click()
    await page.waitForFunction(count => document.querySelectorAll('[data-message-id]').length > count, initialCount)
    assert.ok(await page.locator('[data-message-id]').count() > initialCount)
    const quoting = page.locator('[data-message-id="120"] .reply-preview')
    await quoting.click()
    await page.locator('[data-message-id="1"].message-highlighted').waitFor()
    assert.equal(await page.getByText('正在查看较早的消息', { exact: true }).isVisible(), true)
    const original = page.locator('[data-message-id="1"]')
    const originalText = await original.locator('.message-content').textContent()
    await original.getByRole('button', { name: '引用', exact: true }).click()
    assert.equal(await page.locator('.reply-bar').isVisible(), true)
    assert.equal(await input.evaluate(element => element === document.activeElement), true)
    await input.fill('仅用于验证的本地草稿，不会发送')
    await page.getByRole('button', { name: '取消引用', exact: true }).click()
    assert.equal(await input.inputValue(), '仅用于验证的本地草稿，不会发送')
    await input.fill('')
    const more = original.getByRole('button', { name: '更多', exact: true })
    await more.click()
    const menu = page.getByRole('dialog', { name: '消息操作', exact: true })
    await menu.waitFor()
    assert.equal(await menu.getByRole('button', { name: '仅从我的记录删除', exact: true }).isVisible(), true)
    await menu.getByRole('button', { name: '复制文字', exact: true }).click()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), originalText)
    await more.click()
    await page.keyboard.press('Escape')
    assert.equal(await menu.isVisible(), false)
    assert.equal(await more.evaluate(element => element === document.activeElement), true)
    await page.getByRole('button', { name: '搜索聊天记录', exact: true }).click()
    await page.getByRole('searchbox', { name: '搜索聊天记录', exact: true }).fill(originalText.trim().slice(0, 8))
    await page.getByRole('button', { name: '查找', exact: true }).click()
    await page.locator('.search-result').first().waitFor()
    await page.locator('.search-result').first().click()
    assert.equal(await page.locator('.message-highlighted').count(), 1)
    assert.ok(pureReads.some(url => url.searchParams.has('q')))
    assert.ok(pureReads.some(url => url.searchParams.has('around_id')))
    assert.equal(pureReads.every(url => url.searchParams.get('mark_read') === '0'), true)
    await page.getByRole('button', { name: '收起', exact: true }).click()
    await page.getByRole('button', { name: '返回最新', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.context-banner'))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false)
    const state = await desktop.storageState()
    const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, colorScheme: 'light', reducedMotion: 'reduce', storageState: state })
    contexts.push(mobile)
    const phone = await mobile.newPage()
    phone.on('pageerror', error => errors.push(error.message))
    phone.on('request', request => { if (new URL(request.url()).pathname === '/api/messages' && request.method() === 'POST') mutations.push(request.url()) })
    await phone.goto(new URL('/chat/' + peer, base).href, { waitUntil: 'networkidle' })
    const mobileInput = phone.getByRole('textbox', { name: '消息内容', exact: true })
    await mobileInput.fill('第一行')
    await mobileInput.press('Enter')
    await mobileInput.pressSequentially('第二行')
    assert.equal(await mobileInput.inputValue(), '第一行\n第二行')
    assert.equal(mutations.length, 0, 'mobile Enter does not send a message')
    assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false)
    assert.equal(await phone.locator('.message-action').first().evaluate(element => element.getBoundingClientRect().height >= 44), true, 'touch message actions are at least 44px')
    assert.equal(await phone.locator('.history-button').first().evaluate(element => element.getBoundingClientRect().height >= 44), true, 'touch history action is at least 44px')
    await phone.setViewportSize({ width: 375, height: 430 })
    await phone.waitForFunction(() => Number.parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--visual-viewport-height')) < 500)
    assert.equal(await mobileInput.evaluate(element => element.getBoundingClientRect().bottom <= window.visualViewport.height + window.visualViewport.offsetTop + 2), true, 'composer remains inside the reduced visual viewport')
    await mobileInput.fill('')
    assert.deepEqual(errors, [])
    assert.equal(mutations.length, 0)
    console.log('Private browser checks passed: existing seeded history, #120→#1 quote, copy/Escape/focus, pure search, 375px multiline, keyboard viewport, zero sends')
  } finally { for (const context of contexts) await context.close(); await browser.close() }
})
