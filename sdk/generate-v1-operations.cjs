'use strict';
const fs = require('node:fs');
const path = require('node:path');
const spec = JSON.parse(fs.readFileSync(path.join(__dirname, '../docs/openapi.json'), 'utf8'));
const outputs = [path.join(__dirname, 'v1-operations.mjs'), path.join(__dirname, 'v1-operations.d.ts')];
const operations = [];
function resolve(value) {
  const seen = new Set();
  while (value?.$ref) {
    const reference = value.$ref;
    if (!reference.startsWith('#/') || seen.has(reference)) throw new Error('Unsupported or circular reference: ' + reference);
    seen.add(reference);
    value = reference.slice(2).split('/').map(part => part.replace(/~1/g, '/').replace(/~0/g, '~')).reduce((node, key) => node && Object.hasOwn(node, key) ? node[key] : undefined, spec);
    if (!value) throw new Error('Missing reference: ' + reference);
  }
  return value;
}
for (const [route, item] of Object.entries(spec.paths)) for (const method of ['get','post','put','delete','patch','head','options']) {
  const operation = item[method];
  if (!operation || operation['x-internal'] || route === '/dashboard/session') continue;
  const servers = operation.servers || item.servers || spec.servers;
  if (servers?.[0]?.url !== '/api/v1') throw new Error('Undeclared non-v1 SDK policy: ' + route);
  const security = operation.security ?? spec.security ?? [];
  if (security.length && !security.some(requirement => Object.keys(requirement).every(name => {
    const scheme = resolve(spec.components?.securitySchemes?.[name]);
    return scheme?.type === 'http' && scheme.scheme?.toLowerCase() === 'bearer';
  }))) throw new Error('Unsupported SDK authentication: ' + operation.operationId);
  const parameters = new Map();
  for (const raw of [...(item.parameters || []), ...(operation.parameters || [])]) {
    const parameter = resolve(raw);
    const schema = resolve(parameter.schema) || {};
    parameters.set(parameter.in + ':' + parameter.name, { name: parameter.name, in: parameter.in, required: !!parameter.required, type: schema.type || 'string', ...(schema.enum ? { enum: schema.enum } : {}) });
  }
  const body = resolve(operation.requestBody);
  const contentTypes = Object.entries(operation.responses || {}).filter(([status]) => /^2\d\d$/.test(status)).flatMap(([, response]) => Object.keys(resolve(response)?.content || {}));
  const format = route === '/openapi.json' ? 'raw-json' : contentTypes.some(type => /^(application\/(?:gzip|octet-stream)|image\/)/i.test(type)) ? 'binary' : 'json';
  const bodyType = Object.keys(body?.content || {})[0] || null;
  if (bodyType && bodyType !== 'application/json') throw new Error('Unsupported SDK body format: ' + bodyType);
  if (typeof operation.operationId !== 'string' || !operation.operationId) throw new Error('Missing operationId: ' + method + ' ' + route);
  operations.push([operation.operationId, { method: method.toUpperCase(), path: route, auth: security.length > 0, response: format, params: [...parameters.values()], body: bodyType, bodyRequired: !!body?.required }]);
}
operations.sort((a,b) => a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);
if (new Set(operations.map(([id]) => id)).size !== operations.length) throw new Error('Duplicate SDK operationId');
const moduleText = [
  '// Generated from docs/openapi.json; only v1 non-cookie operations. Do not edit manually.',
  'export const V1_OPERATIONS = Object.freeze(Object.fromEntries([',
  ...operations.map(entry => '  ' + JSON.stringify(entry) + ','),
  '].map(([id, operation]) => [id, Object.freeze({ ...operation, params: Object.freeze(operation.params.map(parameter => Object.freeze(parameter))) })])));',
  '',
].join('\n');
const declarations = [
  '// Generated by node sdk/generate-v1-operations.cjs.',
  'export type OperationId = ' + operations.map(([id]) => JSON.stringify(id)).join(' | ') + ';',
  'export interface OperationParams { path?: Record<string, string | number>; query?: Record<string, string | number | boolean | null | undefined>; body?: Record<string, unknown>; wallId?: string | number | null; }',
  'export interface OperationSpec { method: string; path: string; auth: boolean; response: "json" | "raw-json" | "binary"; params: readonly { name: string; in: string; required: boolean; type: string; enum?: readonly unknown[] }[]; body: string | null; bodyRequired: boolean; }',
  'export declare const V1_OPERATIONS: Readonly<Record<OperationId, OperationSpec>>;',
  '',
].join('\n');
const files = [[outputs[0], moduleText], [outputs[1], declarations]];
if (process.argv.includes('--check')) {
  const stale = files.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text).map(([file]) => path.basename(file));
  if (stale.length) { console.error('Generated SDK files are stale: ' + stale.join(', ')); process.exitCode = 1; }
} else for (const [file, text] of files) fs.writeFileSync(file, text);
const documented = Object.values(spec.paths).reduce((sum,item)=>sum+Object.keys(item).filter(key=>['get','post','put','delete','patch','head','options'].includes(key)).length,0);
console.log(JSON.stringify({ documented, publicOperations: operations.length, policyExcluded: documented - operations.length }));
